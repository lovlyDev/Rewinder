// Extracts the "regular" (outline) and "fill" variants of the Phosphor icons the
// UI uses into one small module. Each phosphor-svelte component carries all six
// weights (~3 KB), so importing components directly would bloat the bundle.
// Run with `npm run icons` after changing the list.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const names = {
  appWindow: 'AppWindow',
  arrowSquareOut: 'ArrowSquareOut',
  caretDown: 'CaretDown',
  caretLeft: 'CaretLeft',
  caretRight: 'CaretRight',
  check: 'Check',
  checkCircle: 'CheckCircle',
  clock: 'ClockCounterClockwise',
  folderOpen: 'FolderOpen',
  gear: 'Gear',
  globe: 'Globe',
  image: 'Image',
  info: 'Info',
  keyboard: 'Keyboard',
  lightning: 'Lightning',
  magnifyingGlass: 'MagnifyingGlass',
  minus: 'Minus',
  palette: 'Palette',
  pause: 'Pause',
  play: 'Play',
  power: 'Power',
  restore: 'ArrowCounterClockwise',
  sliders: 'SlidersHorizontal',
  stack: 'Stack',
  warning: 'WarningCircle',
  x: 'X',
  monitor: 'Monitor',
  layouts: 'SquaresFour',
  trash: 'Trash',
  eye: 'Eye',
  eyeSlash: 'EyeSlash',
  shield: 'ShieldCheck',
  download: 'DownloadSimple',
  plus: 'Plus',
  refresh: 'ArrowsClockwise',
  github: 'GithubLogo',
  user: 'User',
};

// Action glyphs whose Phosphor "fill" variant is the glyph cut out of a filled
// square or circle. They never fill: a close button must not turn into a box.
const still = new Set(['x', 'minus', 'check', 'power', 'arrowSquareOut', 'caretDown', 'caretLeft', 'caretRight', 'plus', 'refresh']);

const lib = new URL('../node_modules/phosphor-svelte/lib/', import.meta.url);
const weight = (src, w) => {
  const m = src.match(new RegExp(`weight === "${w}"\\}\\s*([\\s\\S]*?)\\s*\\{:else`));
  if (!m) throw new Error(`no ${w} weight`);
  return m[1].replace(/\s+/g, ' ').trim();
};

let out = '// Generated by scripts/icons.mjs from phosphor-svelte (MIT). Do not edit.\n';
out += 'export const icons = {\n';
for (const [key, file] of Object.entries(names)) {
  const src = readFileSync(new URL(`${file}.svelte`, lib), 'utf8');
  const regular = weight(src, 'regular');
  const fill = still.has(key) ? regular : weight(src, 'fill');
  out += `  ${key}: [${JSON.stringify(regular)}, ${JSON.stringify(fill)}],\n`;
}
out += '} as const;\n\nexport type IconName = keyof typeof icons;\n';
writeFileSync(fileURLToPath(new URL('../src/ui/icon/icons.ts', import.meta.url)), out);
console.log(`icons: ${Object.keys(names).length} written`);
